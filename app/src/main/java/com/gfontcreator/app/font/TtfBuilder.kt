package com.gfontcreator.app.font

import java.io.ByteArrayOutputStream

/**
 * 大端二进制写入器（TTF 全部字段为 big-endian）
 */
class ByteWriter {
    private val out = ByteArrayOutputStream(64 * 1024)

    fun u8(v: Int) { out.write(v and 0xFF) }
    fun u16(v: Int) { out.write((v shr 8) and 0xFF); out.write(v and 0xFF) }
    fun i16(v: Int) { u16(v and 0xFFFF) }
    fun u32(v: Long) {
        out.write(((v shr 24).toInt()) and 0xFF)
        out.write(((v shr 16).toInt()) and 0xFF)
        out.write(((v shr 8).toInt()) and 0xFF)
        out.write((v.toInt()) and 0xFF)
    }
    fun i32(v: Int) { u32(v.toLong() and 0xFFFFFFFFL) }
    fun bytes(b: ByteArray) { out.write(b) }

    /** 4 字节对齐填充 */
    fun pad4() {
        while (size() % 4 != 0) u8(0)
    }

    fun size(): Int = out.size()

    fun toByteArray(): ByteArray = out.toByteArray()
}

/**
 * 表校验和（ref.md 4.5：TTF 是多 table 的二进制容器）
 * checksumCalculation: 32 位累加和（mod 2^32），不足 4 字节补 0
 */
object Checksum {
    fun calculate(data: ByteArray): Long {
        var sum = 0L
        var i = 0
        while (i < data.size) {
            val b0 = data[i].toLong() and 0xFF
            val b1 = if (i + 1 < data.size) data[i + 1].toLong() and 0xFF else 0L
            val b2 = if (i + 2 < data.size) data[i + 2].toLong() and 0xFF else 0L
            val b3 = if (i + 3 < data.size) data[i + 3].toLong() and 0xFF else 0L
            sum = (sum + ((b0 shl 24) or (b1 shl 16) or (b2 shl 8) or b3)) and 0xFFFFFFFFL
            i += 4
        }
        return sum
    }
}

/**
 * 组装完整 TTF 文件（纯 Kotlin 实现，ref.md 4.5 路径 A 的端侧替代）。
 *
 * fonttools 在 Android 上需嵌入 Python 运行时（体积大、启动慢），
 * 因此核心表由 Kotlin 直接编码 —— 符合离线优先与 APK 体积约束。
 *
 * 表清单：head / hhea / hmtx / maxp / cmap / loca / glyf / name / OS/2 / post
 */
object TtfBuilder {

    const val UNITS_PER_EM = 1024
    private const val ASCENDER = 880
    private const val DESCENDER = -144
    private const val LINE_GAP = 0

    /** 字体元数据 */
    data class Metadata(
        val familyName: String,
        val subfamilyName: String = "Regular",
        val fullName: String = familyName,
        val postScriptName: String = familyName.replace(" ", ""),
        val version: String = "Version 1.000",
        val copyright: String = "Generated by GFontCreator",
        val description: String = "Handwriting font generated on device",
    )

    /** 单个字形数据 */
    data class GlyphData(
        val outline: com.gfontcreator.app.vectorize.GlyphOutline?,
        /** advance width（em 单位） */
        val advanceWidth: Int = UNITS_PER_EM,
    )

    /**
     * @param glyphs 码位 → 字形数据
     */
    fun build(glyphs: List<Pair<Int, GlyphData>>, meta: Metadata): ByteArray {
        val sorted = glyphs.sortedBy { it.first }
        // gid0 = .notdef，其后按码位升序
        val glyphList = ArrayList<GlyphData>(sorted.size + 1)
        glyphList.add(GlyphData(null))
        val codeToGid = HashMap<Int, Int>(sorted.size)
        sorted.forEachIndexed { i, (cp, g) ->
            codeToGid[cp] = i + 1
            glyphList.add(g)
        }

        val glyf = buildGlyfTable(glyphList)
        val loca = buildLocaTable(glyphList)
        val cmap = buildCmapTable(codeToGid)
        val hmtx = buildHmtxTable(glyphList)
        val head = buildHeadTable(glyphList)
        val hhea = buildHheaTable(glyphList.size)
        val maxp = buildMaxpTable(glyphList)
        val name = buildNameTable(meta)
        val os2 = buildOs2Table()
        val post = buildPostTable()

        val tables = linkedMapOf(
            "OS/2" to os2, "cmap" to cmap, "glyf" to glyf, "head" to head,
            "hhea" to hhea, "hmtx" to hmtx, "loca" to loca, "maxp" to maxp,
            "name" to name, "post" to post,
        )
        return assemble(tables)
    }

    // ---------- sfnt 容器组装 ----------

    private fun assemble(tables: LinkedHashMap<String, ByteArray>): ByteArray {
        val numTables = tables.size
        var searchRange = 1; var entrySelector = 0
        while (searchRange * 2 <= numTables) { searchRange *= 2; entrySelector++ }
        searchRange *= 16

        val sorted = tables.entries.sortedBy { tag(it.key) }
        // 表目录（含偏移，先占位）
        val dirSize = 12 + numTables * 16
        var offset = dirSize
        data class Entry(val tag: String, val checksum: Long, val offset: Int, val length: Int)
        val entries = ArrayList<Entry>(numTables)
        for ((tag, data) in sorted) {
            entries.add(Entry(tag, Checksum.calculate(data), offset, data.size))
            offset += (data.size + 3) and 0x7FFFFFFC.toInt()
        }

        val header = ByteWriter()
        header.u32(0x00010000) // sfntVersion: TrueType
        header.u16(numTables)
        header.u16(searchRange)
        header.u16(entrySelector)
        header.u16(numTables * 16 - searchRange)
        for (e in entries) {
            writeTag(header, e.tag)
            header.u32(e.checksum)
            header.u32(e.offset.toLong())
            header.u32(e.length.toLong())
        }

        val body = ByteWriter()
        val headDataOffset = intArrayOf(0)
        for ((tag, data) in sorted) {
            if (tag == "head") headDataOffset[0] = body.size() + dirSize
            body.bytes(data)
            body.pad4()
        }

        val result = header.toByteArray() + body.toByteArray()
        // checkSumAdjustment = 0xB1B0AFBA - (整个文件校验和，head 该字段置 0 计算)
        val zeroed = result.copyOf()
        for (i in 0 until 4) zeroed[headDataOffset[0] + 8 + i] = 0
        val adjustment = (0xB1B0AFBAL - Checksum.calculate(zeroed)) and 0xFFFFFFFFL
        val adj = intArrayOf(
            ((adjustment shr 24) and 0xFF).toInt(),
            ((adjustment shr 16) and 0xFF).toInt(),
            ((adjustment shr 8) and 0xFF).toInt(),
            (adjustment and 0xFF).toInt(),
        )
        for (i in 0 until 4) result[headDataOffset[0] + 8 + i] = adj[i].toByte()
        return result
    }

    private fun writeTag(w: ByteWriter, tag: String) {
        val t = tag.padEnd(4).substring(0, 4)
        for (c in t) w.u8(c.code)
    }

    private fun tag(s: String): Int {
        val t = s.padEnd(4).substring(0, 4)
        var v = 0L
        for (c in t) v = (v shl 8) or (c.code.toLong() and 0xFF)
        return v.toInt()
    }

    // ---------- 各表编码 ----------

    private fun buildHeadTable(glyphs: List<GlyphData>): ByteArray {
        val w = ByteWriter()
        w.u32(0x00010000) // version
        w.u32(0x00010000) // fontRevision 1.0
        w.u32(0)          // checkSumAdjustment（组装时回填）
        w.u32(0x5F0F3CF5) // magicNumber
        w.u16(0x000B)     // flags
        w.u16(UNITS_PER_EM)
        // created/modified: LONGDATETIME（8 字节，自 1904-01-01 起秒数；0 会被 Windows 显示为 1904 年）
        // 2082844800 = 1904-01-01 到 1970-01-01 的秒数偏移
        val macNow = (System.currentTimeMillis() / 1000L + 2082844800L) and 0xFFFFFFFFL
        w.u32(macNow ushr 32); w.u32(macNow)   // created
        w.u32(macNow ushr 32); w.u32(macNow)   // modified
        var xMin = Int.MAX_VALUE; var yMin = Int.MAX_VALUE
        var xMax = Int.MIN_VALUE; var yMax = Int.MIN_VALUE
        for (g in glyphs) if (g.outline != null) {
            for (c in g.outline.contours) for (p in c.points) {
                val x = p.x.toInt(); val y = p.y.toInt()
                if (x < xMin) xMin = x; if (y < yMin) yMin = y
                if (x > xMax) xMax = x; if (y > yMax) yMax = y
            }
        }
        if (xMin == Int.MAX_VALUE) { xMin = 0; yMin = 0; xMax = 0; yMax = 0 }
        w.i16(xMin); w.i16(yMin); w.i16(xMax); w.i16(yMax)
        w.u16(0)          // macStyle
        w.u16(8)          // lowestRecPPEM
        w.i16(-2)         // fontDirectionHint（左到右 = -2）
        w.i16(1)          // indexToLocFormat: 1 = long loca（与 buildLocaTable 配套）
        w.i16(0)          // glyphDataFormat
        return w.toByteArray()
    }

    private fun buildHheaTable(numGlyphs: Int): ByteArray {
        val w = ByteWriter()
        w.u32(0x00010000)
        w.i16(ASCENDER); w.i16(DESCENDER); w.i16(LINE_GAP)
        w.u16(UNITS_PER_EM) // advanceWidthMax
        w.i16(0); w.i16(0)  // minLeftSideBearing / minRightSideBearing
        w.i16(UNITS_PER_EM) // xMaxExtent
        w.i16(1); w.i16(0)  // caretSlopeRise=1 / caretSlopeRun=0
        w.i16(0)            // caretOffset
        repeat(4) { w.i16(0) } // reserved
        w.i16(0)            // metricDataFormat
        w.u16(numGlyphs)    // numberOfHMetrics
        return w.toByteArray()
    }

    private fun buildHmtxTable(glyphs: List<GlyphData>): ByteArray {
        val w = ByteWriter()
        for (g in glyphs) {
            w.u16(g.advanceWidth)
            w.i16(0) // lsb
        }
        return w.toByteArray()
    }

    private fun buildMaxpTable(glyphs: List<GlyphData>): ByteArray {
        val w = ByteWriter()
        // 按实际轮廓几何计算 maxPoints / maxContours（严格校验器会核对）
        var maxPoints = 0; var maxContours = 0
        for (g in glyphs) g.outline?.let { o ->
            var p = 0
            for (c in o.contours) p += c.points.size
            if (p > maxPoints) maxPoints = p
            if (o.contours.size > maxContours) maxContours = o.contours.size
        }
        w.u32(0x00010000) // version 1.0
        w.u16(glyphs.size)
        w.u16(maxPoints); w.u16(maxContours)
        w.u16(0); w.u16(0)     // maxCompositePoints / maxCompositeContours
        w.u16(2); w.u16(0)     // maxZones / maxTwilightPoints
        w.u16(0)               // maxStorage
        w.u16(0)               // maxFunctionDefs
        w.u16(0)               // maxInstructionDefs
        w.u16(0)               // maxStackElements
        w.u16(0)               // maxSizeOfInstructions
        w.u16(0)               // maxComponentElements
        w.u16(0)               // maxComponentDepth
        return w.toByteArray()
    }

    /** cmap: format 4（BMP 段映射，覆盖 6900 个 BMP 码位足够） */
    private fun buildCmapTable(codeToGid: Map<Int, Int>): ByteArray {
        val codes = codeToGid.keys.sorted()
        data class Seg(val start: Int, val end: Int, val delta: Int)
        val segs = ArrayList<Seg>()
        var sStart = -1; var sEnd = -1; var sDelta = 0
        for (cp in codes) {
            val delta = codeToGid[cp]!! - cp
            if (sStart == -1) { sStart = cp; sEnd = cp; sDelta = delta }
            else if (cp == sEnd + 1 && delta == sDelta) { sEnd = cp }
            else { segs.add(Seg(sStart, sEnd, sDelta)); sStart = cp; sEnd = cp; sDelta = delta }
        }
        if (sStart != -1) segs.add(Seg(sStart, sEnd, sDelta))
        segs.add(Seg(0xFFFF, 0xFFFF, 1)) // 终止段

        val segCount = segs.size
        var searchRange = 1; var entrySelector = 0
        while (searchRange * 2 <= segCount) { searchRange *= 2; entrySelector++ }
        searchRange *= 2
        val rangeShift = segCount * 2 - searchRange

        fun subtable(): ByteWriter {
            val w = ByteWriter()
            val lenPos = w.size() + 2
            w.u16(4); w.u16(0); w.u16(0) // format / length 回填 / language
            w.u16(segCount * 2)
            w.u16(searchRange); w.u16(entrySelector); w.u16(rangeShift)
            for (s in segs) w.u16(s.end)
            w.u16(0) // reservedPad
            for (s in segs) w.u16(s.start)
            for (s in segs) w.u16(((s.delta % 65536) + 65536) % 65536)
            for (s in segs) w.u16(0) // idRangeOffset：全部用 delta 映射
            val bytes = w.toByteArray()
            bytes[lenPos] = ((bytes.size shr 8) and 0xFF).toByte()
            bytes[lenPos + 1] = (bytes.size and 0xFF).toByte()
            val r = ByteWriter(); r.bytes(bytes); return r
        }

        val w = ByteWriter()
        w.u16(0) // version
        w.u16(1) // numTables：仅 Windows BMP（两条记录共用 offset 12 会重叠，fontTools/Windows 均拒绝）
        w.u16(3); w.u16(1); w.u32(12) // (3,1) offset 12
        w.bytes(subtable().toByteArray())
        return w.toByteArray()
    }

    /**
     * loca 表（long format，4 字节绝对偏移）。
     * 6900 字全字库的 glyf 表远大于 short format（u16/2）能表示的 128 KB 上限，
     * 必须使用 long format，否则偏移溢出导致 Windows 无法定位字形。
     * 与 head.indexToLocFormat = 1 配套。
     */
    private fun buildLocaTable(glyphs: List<GlyphData>): ByteArray {
        val w = ByteWriter()
        var offset = 0
        for (g in glyphs) {
            w.u32(offset.toLong()) // long format：glyf 内绝对偏移
            offset += paddedGlyfEntry(g).size
        }
        w.u32(offset.toLong()) // 末尾哨兵
        return w.toByteArray()
    }

    /** 单个 glyf 条目（含 2 字节对齐填充），loca 与 glyf 必须使用同一布局 */
    private fun paddedGlyfEntry(g: GlyphData): ByteArray {
        val entry = glyfEntry(g)
        return if (entry.size % 2 != 0) entry + byteArrayOf(0) else entry
    }

    /** glyf 表 = 各字形条目顺序拼接 */
    private fun buildGlyfTable(glyphs: List<GlyphData>): ByteArray {
        val w = ByteWriter()
        for (g in glyphs) w.bytes(paddedGlyfEntry(g))
        return w.toByteArray()
    }

    private fun glyfEntry(g: GlyphData): ByteArray {
        val outline = g.outline ?: return emptySimpleGlyph()
        if (outline.contours.isEmpty()) return emptySimpleGlyph()
        return buildGlyfEntryCorrect(outline)
    }

    private fun buildGlyfEntryCorrect(outline: com.gfontcreator.app.vectorize.GlyphOutline): ByteArray {
        val w = ByteWriter()
        var xMin = Int.MAX_VALUE; var yMin = Int.MAX_VALUE
        var xMax = Int.MIN_VALUE; var yMax = Int.MIN_VALUE
        for (c in outline.contours) for (p in c.points) {
            val x = p.x.toInt(); val y = p.y.toInt()
            if (x < xMin) xMin = x; if (y < yMin) yMin = y
            if (x > xMax) xMax = x; if (y > yMax) yMax = y
        }
        w.i16(outline.contours.size)
        w.i16(xMin); w.i16(yMin); w.i16(xMax); w.i16(yMax)

        var acc = -1
        for (c in outline.contours) {
            acc += c.points.size
            w.u16(acc)
        }
        w.u16(0) // instructionLength = 0

        val allPoints = outline.contours.flatMap { it.points }
        val flags = ArrayList<Int>(allPoints.size)
        val xs = ArrayList<Int>(allPoints.size)
        val ys = ArrayList<Int>(allPoints.size)
        var prevX = 0; var prevY = 0
        for (p in allPoints) {
            val x = p.x.toInt(); val y = p.y.toInt()
            val dx = x - prevX; val dy = y - prevY
            var flag = 0
            if (p.onCurve) flag = flag or 0x01
            // x 短向量：0x02=1 字节增量，0x10=增量为正/零；两者都不设时为 int16
            when {
                dx == 0 -> flag = flag or 0x10
                dx in 1..255 -> { flag = flag or 0x02 or 0x10; xs.add(dx) }
                dx in -255..-1 -> { flag = flag or 0x02; xs.add(-dx) }
                else -> xs.add(dx)
            }
            when {
                dy == 0 -> flag = flag or 0x20
                dy in 1..255 -> { flag = flag or 0x04 or 0x20; ys.add(dy) }
                dy in -255..-1 -> { flag = flag or 0x04; ys.add(-dy) }
                else -> ys.add(dy)
            }
            flags.add(flag)
            prevX = x; prevY = y
        }
        // flags（支持 REPEAT 压缩）
        var i = 0
        while (i < flags.size) {
            val f = flags[i]
            var run = 1
            while (i + run < flags.size && flags[i + run] == f && run < 255) run++
            if (run > 1) { w.u8(f or 0x08); w.u8(run - 1) } else w.u8(f)
            i += run
        }
        var xi = 0
        for (f in flags) {
            if (f and 0x02 != 0) w.u8(xs[xi++])
            else if (f and 0x10 == 0) w.i16(xs[xi++])
        }
        var yi = 0
        for (f in flags) {
            if (f and 0x04 != 0) w.u8(ys[yi++])
            else if (f and 0x20 == 0) w.i16(ys[yi++])
        }
        return w.toByteArray()
    }

    private fun emptySimpleGlyph(): ByteArray {
        val w = ByteWriter()
        w.i16(0) // numberOfContours = 0（空字形）
        w.i16(0); w.i16(0); w.i16(0); w.i16(0)
        return w.toByteArray()
    }

    /** name 表：Windows platform (3,1) UTF-16BE */
    private fun buildNameTable(meta: Metadata): ByteArray {
        data class NameRec(val nameId: Int, val value: String)
        val recs = listOf(
            NameRec(0, meta.copyright),
            NameRec(1, meta.familyName),
            NameRec(2, meta.subfamilyName),
            NameRec(3, "GFontCreator;${meta.fullName};1.000"),
            NameRec(4, meta.fullName),
            NameRec(5, meta.version),
            NameRec(6, meta.postScriptName),
            NameRec(9, "GFontCreator"),
            NameRec(10, meta.description),
        )
        val stringOffset = 6 + recs.size * 12
        val w = ByteWriter()
        w.u16(0); w.u16(recs.size); w.u16(stringOffset)
        val strings = ByteWriter()
        var strAcc = 0
        for (r in recs) {
            val utf16 = r.value.toByteArray(Charsets.UTF_16BE)
            w.u16(3); w.u16(1); w.u16(0x0409) // Windows / Unicode BMP / en-US
            w.u16(r.nameId)
            w.u16(utf16.size)
            w.u16(strAcc)
            strings.bytes(utf16)
            strAcc += utf16.size
        }
        w.bytes(strings.toByteArray())
        return w.toByteArray()
    }

    /**
     * OS/2 表 version 2（90 字节，严格按 OpenType 规范字段顺序）。
     * 字段顺序：version, xAvgCharWidth, usWeightClass, usWidthClass, fsType,
     *   ySubscriptXSize/YSize/XOffset/YOffset, ySuperscriptXSize/YSize/XOffset/YOffset,
     *   yStrikeoutSize/Position, sFamilyClass, panose(10), ulUnicodeRange1..4, achVendID(4),
     *   fsSelection, usFirstCharIndex, usLastCharIndex, sTypoAscender/Descender/LineGap,
     *   usWinAscent/Descent, (v2) sxHeight, sCapHeight, usDefaultChar, usBreakChar, usMaxContext
     */
    private fun buildOs2Table(): ByteArray {
        val v = ByteWriter()
        v.u16(0x0002)                 // version 2.0（2 字节，非 4 字节）
        v.i16(500)                    // xAvgCharWidth
        v.u16(400)                    // usWeightClass
        v.u16(5)                      // usWidthClass
        v.u16(0x0000)                 // fsType: installable
        v.i16(600); v.i16(600); v.i16(0); v.i16(-40)   // ySubscript XSize/YSize/XOffset/YOffset
        v.i16(600); v.i16(600); v.i16(0); v.i16(40)    // ySuperscript XSize/YSize/XOffset/YOffset
        v.i16(50); v.i16(-100)        // yStrikeoutSize / yStrikeoutPosition
        v.i16(0)                      // sFamilyClass
        repeat(10) { v.u8(0) }        // panose（10 字节）
        // ulUnicodeRange1..4：覆盖基本拉丁 + 拉丁扩展 + CJK 统一汉字（6900 字集范围）
        v.u32(0x00000003L)            // Basic Latin (bit0) + Latin-1 Supplement (bit1)
        v.u32(0x00000000L)
        v.u32(0x00000000L)
        v.u32(0x20000000L)            // CJK Unified Ideographs (bit30)
        writeTag(v, "GFC ")           // achVendID
        v.u16(0x0040)                 // fsSelection REGULAR
        v.u16(0x0020)                 // usFirstCharIndex
        v.u16(0xFFFF)                 // usLastCharIndex
        v.i16(ASCENDER)               // sTypoAscender
        v.i16(DESCENDER)              // sTypoDescender
        v.i16(LINE_GAP)               // sTypoLineGap
        v.u16(UNITS_PER_EM)           // usWinAscent
        v.u16(UNITS_PER_EM)           // usWinDescent
        // —— version >= 1 ——
        v.u32(0x00000001L)            // ulCodePageRange1（bit0 = Basic Latin/ASCII）
        v.u32(0x20000000L)            // ulCodePageRange2（bit54 = GB2312，字集为 GB2312 常用汉字）
        // —— version >= 2 ——
        v.i16(500)                    // sxHeight
        v.i16(700)                    // sCapHeight
        v.u16(0)                      // usDefaultChar
        v.u16(0x0020)                 // usBreakChar (space)
        v.u16(2)                      // usMaxContext
        return v.toByteArray()
    }

    private fun buildPostTable(): ByteArray {
        val w = ByteWriter()
        w.u32(0x00030000) // version 3.0（不含字形名）
        w.i32(0); w.i32(0) // italicAngle
        w.i16(-100)        // underlinePosition
        w.i16(50)          // underlineThickness
        w.u32(0)           // isFixedPitch
        repeat(4) { w.u32(0) } // min/max mem
        return w.toByteArray()
    }
}
